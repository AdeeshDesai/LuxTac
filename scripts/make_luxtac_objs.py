"""Generate the LuxTac objects: 4 shapes x 4 in-plane orientations, plus the insertion peg.

Cross-sections (mm), from the CAD of the printed prisms:

    cuboid    20.0 x 20.0 square
    cylinder  D 25.0
    ellipse   40.0 x 20.0   (40 across the pad, 20 along the grip axis)
    peg       D 15.0

FRAME. Metres, centred on x and y (the grip axis is y), cross-section centre at
z = Z_CENTRE_MM. The task stages the plug origin 43.2mm from the fingertip midpoint
(set by length 0.054 in the asset table) with mesh +z toward the hand, so 45.2mm puts
the cross-section centre on the pad centre, 2.0mm behind the fingertip frame.

ORIENTATION. The prism's long axis lies in the x-z plane: z is along the finger (the
36mm gel dimension, the taxel columns) and x is across it (the 18mm dimension, the
taxel rows). The long axis is at 0 deg ("vertical"), 90 deg ("horizontal"), 45 or
135 deg. Each pose is baked into its own mesh.

LENGTH. The printed objects are 75mm (peg 90mm); the meshes are cut to 40mm. The gel
is 18 x 36mm, so nothing beyond ~26mm from centre can touch it, and a full-length
prism at 45 deg would reach back into the hand.

usage: make_luxtac_objs.py <out_mesh_dir> <out_urdf_dir>
"""
import sys
from pathlib import Path
import numpy as np
import trimesh

mesh_dir, urdf_dir = Path(sys.argv[1]), Path(sys.argv[2])
mesh_dir.mkdir(parents=True, exist_ok=True); urdf_dir.mkdir(parents=True, exist_ok=True)
MM, Z_CENTRE_MM = 0.001, 45.2
# Mesh length, mm. Every scored object is cut to 40mm (see LENGTH above).
LENGTH_MM = {}
DEFAULT_LENGTH_MM = 40.0
DENSITY = 1240.0                      # solid PLA
# Every object is given this mass, with the inertia scaled by the same factor.
MASS_KG = 1.5

def section(name, n=96):
    """Cross-section polygon in the x-y plane, mm. x is across the pad, y the grip axis."""
    if name == "cuboid":   return np.array([[-10,-10],[10,-10],[10,10],[-10,10]], float)
    t = np.linspace(0, 2*np.pi, n, endpoint=False)
    if name == "cylinder": return np.c_[12.5*np.cos(t), 12.5*np.sin(t)]
    if name == "peg":      return np.c_[7.5*np.cos(t), 7.5*np.sin(t)]
    if name == "ellipse":  return np.c_[20.0*np.cos(t), 10.0*np.sin(t)]
    raise KeyError(name)

def prism(poly, h):
    """Convex cross-section polygon (N,2) in x-y, extruded h along +z.

    Written out rather than taken from trimesh.creation.extrude_polygon because that
    path needs shapely, which is not in this env. Every section here is convex, so a
    triangle fan from the centroid is a valid cap triangulation and the hull is exact.
    Winding: caps face outward (-z cap reversed), sides wound to match.
    """
    n = len(poly)
    c = poly.mean(axis=0)
    bot = np.c_[poly, np.zeros(n)]
    top = np.c_[poly, np.full(n, h)]
    cb = np.array([[c[0], c[1], 0.0]]); ct = np.array([[c[0], c[1], h]])
    V = np.vstack([bot, top, cb, ct])
    ib, it = 2*n, 2*n+1
    F = []
    for i in range(n):
        j = (i+1) % n
        F.append([ib, j, i])                  # bottom cap, facing -z
        F.append([it, n+i, n+j])               # top cap, facing +z
        F.append([i, j, n+j])                  # side
        F.append([i, n+j, n+i])
    m = trimesh.Trimesh(vertices=V, faces=np.array(F), process=True)
    m.fix_normals()
    return m


SHAPES = ("cuboid", "cylinder", "ellipse", "peg")
# Angle of the prism long axis from the finger axis (tip to hand) in the pad plane.
# deg45 and deg135 put the contact line on opposite diagonals; deg135 is the mirrored
# control for the real 45 deg grasps.
ANGLES = {"vert": 0.0, "horz": 90.0, "deg45": 45.0, "deg135": 135.0}

URDF = """<?xml version="1.0"?>
<!-- {desc}
     Generated by scripts/make_luxtac_objs.py. Metres, centred on x,y, cross-section
     centre at z = {zc:.4f} (the pad centre once staged). Long axis at {ang:.0f} deg in
     the x-z plane: 0 = along the finger, 90 = across it. Length {len_mm:.0f}mm,
     mass {mass:.6f} kg.

     The link is named 'cube' because TacSL resolves the indenter link by name. -->
<robot name="{name}">
    <link name="cube">
        <visual>
            <geometry><mesh filename="../mesh/{name}.obj"/></geometry>
            <material name="black"><color rgba="0.05 0.05 0.05 1"/></material>
        </visual>
        <collision>
            <geometry><mesh filename="../mesh/{name}.obj"/></geometry>
            <sdf resolution="256"/>  <!-- {vox:.3f}mm voxels -->
        </collision>
        <inertial>
            <origin rpy="0 0 0" xyz="0 0 {zc:.4f}"/>
            <mass value="{mass:.6f}"/>
            <inertia ixx="{ixx:.6e}" ixy="0" ixz="0" iyy="{iyy:.6e}" iyz="0" izz="{izz:.6e}"/>
        </inertial>
    </link>
</robot>
"""

print(f"{'object':28s} {'bbox x,y,z mm':>26s} {'mass g':>8s}")
rows = []
for sh in SHAPES:
    for otag, ang in ANGLES.items():
        poly = section(sh)
        length = LENGTH_MM.get((sh, otag), DEFAULT_LENGTH_MM)
        m = prism(poly, length)
        m.apply_translation([0, 0, -length/2.0])          # long axis on z, centred
        m.apply_transform(trimesh.transformations.rotation_matrix(
            np.deg2rad(ang), [0, 1, 0]))                      # rotate in the x-z plane
        c = m.bounds.mean(axis=0)
        m.apply_translation([-c[0], -c[1], Z_CENTRE_MM - c[2]])
        m.apply_scale(MM)
        m.density = DENSITY
        name = f"luxtac_{sh}_{otag}"
        m.export(mesh_dir / f"{name}.obj")
        I = m.moment_inertia * (MASS_KG / m.mass)
        d = (m.bounds[1]-m.bounds[0])/MM
        (urdf_dir / f"{name}.urdf").write_text(URDF.format(
            desc=f"{sh}, long axis at {ang:.0f} deg in the pad plane.",
            name=name, ang=ang, zc=Z_CENTRE_MM*MM, len_mm=length, dens=DENSITY,
            mass=MASS_KG, ixx=I[0,0], iyy=I[1,1], izz=I[2,2],
            vox=max(d)/256.0))
        print(f"{name:28s} {d[0]:7.2f}{d[1]:7.2f}{d[2]:7.2f}   {MASS_KG*1e3:8.1f}")
        rows.append((name, sh, otag, MASS_KG))

# Insertion peg for teleop: the 15mm peg at 90mm length. Its top is where the 40mm
# peg's top is (clear of the hand) and it extends 70mm below the pad centre.
INSERT_LEN_MM, INSERT_TOP_MM = 90.0, Z_CENTRE_MM + DEFAULT_LENGTH_MM / 2.0
INSERT_MASS_KG = MASS_KG                # same as the scored objects
m = prism(section("peg"), INSERT_LEN_MM)
m.apply_translation([0, 0, INSERT_TOP_MM - INSERT_LEN_MM])
m.apply_scale(MM)
m.density = DENSITY
name = "luxtac_peg_insert"
m.export(mesh_dir / f"{name}.obj")
I = m.moment_inertia * (INSERT_MASS_KG / m.mass)
d = (m.bounds[1]-m.bounds[0])/MM
(urdf_dir / f"{name}.urdf").write_text(URDF.format(
    desc="peg, 90mm long, for insertion teleop.",
    name=name, ang=0.0, zc=Z_CENTRE_MM*MM, len_mm=INSERT_LEN_MM, dens=DENSITY,
    mass=INSERT_MASS_KG, ixx=I[0,0], iyy=I[1,1], izz=I[2,2], vox=max(d)/256.0))
print(f"{name:28s} {d[0]:7.2f}{d[1]:7.2f}{d[2]:7.2f}   {INSERT_MASS_KG*1e3:8.1f}")
rows.append((name, "peg", "insert", INSERT_MASS_KG))
print(f"\n{len(rows)} meshes -> {mesh_dir}\n{len(rows)} urdfs  -> {urdf_dir}")
